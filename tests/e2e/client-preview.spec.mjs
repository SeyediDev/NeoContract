import {test,expect} from '@playwright/test';

for(const width of [1440,390])test(`isolated customer preview: filters, details and keyboard at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:1000});
 const errors=[],apiCalls=[],writes=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))apiCalls.push(r.url());if(!['GET','HEAD'].includes(r.method()))writes.push(r.url());});
 await page.goto('/client-preview.html');await page.evaluate(()=>document.fonts.ready);
 await expect(page.locator('#cp-match')).toContainText('۳۶۰');
 await expect(page.locator('#cp-table tbody tr')).toHaveCount(8);
 const first=await page.locator('#cp-table tbody').innerText();
 await page.getByRole('button',{name:'بعدی',exact:true}).click();
 expect(await page.locator('#cp-table tbody').innerText()).not.toBe(first);
 await page.getByRole('button',{name:'قبلی',exact:true}).click();
 await page.locator('[name=q]').fill('SAMPLE-0360');
 await expect(page.locator('#cp-table tbody tr')).toHaveCount(1);
 await page.getByRole('button',{name:'ورودی و خروجی',exact:true}).focus();await page.keyboard.press('Enter');
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.locator('#cp-detail-body')).toContainText('sample-request-360');
 await expect(page.locator('#cp-detail-body pre').first()).toContainText('[REDACTED]');
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.getByRole('button',{name:'ورودی و خروجی',exact:true})).toBeFocused();
 await page.locator('[name=q]').fill('never-matches');
 await expect(page.locator('#cp-table')).toContainText('فراخوانی مطابق فیلتر پیدا نشد');
 await expect(page.locator('#cp-kpis strong').nth(2)).toHaveText('—');
 await page.getByRole('button',{name:'پاک‌کردن فیلترها'}).click();
 await expect(page.locator('#cp-match')).toContainText('۳۶۰');
 await page.getByRole('button',{name:'فیلتر پاسخ 429'}).click();
 await expect(page.locator('[name=status]')).toHaveValue('429');
 await expect(page.locator('#cp-table tbody tr').first()).toContainText('429');
 await page.locator('[name=q]').fill('rate_limited');
 await expect(page.locator('#cp-match')).not.toContainText('۰ فراخوانی');
 await page.locator('[name=service]').selectOption('identity-check');
 await page.locator('[name=hours]').selectOption('6');
 await expect(page.locator('#cp-table tbody tr').first()).toContainText('استعلام هویت');
 await page.locator('#cp-trend summary').click();
 await expect(page.locator('#cp-trend tbody tr')).toHaveCount(6);
 await page.getByRole('button',{name:'پاک‌کردن فیلترها'}).click();
 await page.locator('[name=hours]').selectOption('1');
 await expect(page.locator('#cp-trend circle')).toHaveCount(2);
 await page.getByRole('button',{name:'پاک‌کردن فیلترها'}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(await page.locator('img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0))).toBe(true);
 await expect(page.getByRole('img',{name:'مرکز رایان'})).toBeVisible();
 expect(errors).toEqual([]);expect(apiCalls).toEqual([]);expect(writes).toEqual([]);
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:`artifacts/client-preview-${width}.png`,fullPage:true});
});
