import {test,expect} from '@playwright/test';
const tenant='00000000-0000-0000-0000-000000000002';
const headers={'X-Tenant-Id':tenant};
for(const width of [1440,390])test(`contract dossier has stable navigation, searchable text and honest gaps at ${width}px`,async({page,request},testInfo)=>{
 await page.setViewportSize({width,height:width===390?844:760});
 await page.addInitScript(id=>sessionStorage.setItem('neocontract-active-tenant',id),tenant);
 const data=await(await request.get('/api/bootstrap',{headers})).json(),c=data.contracts.find(c=>c.title.includes('انتخاب'));
 const before=await(await request.get('/api/contracts/'+c.id,{headers})).json();
 const errors=[],writes=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/')&&['POST','PUT','PATCH','DELETE'].includes(r.method()))writes.push(new URL(r.url()).pathname);});
 await page.goto('/#view=contracts');await page.locator(`[data-action="contract-detail"][data-id="${c.id}"]`).first().click();
 const dialog=page.getByRole('dialog'),tabs=dialog.getByRole('tablist'),panel=dialog.getByRole('tabpanel');
 await expect(dialog.locator('[data-action="contract-neo"]')).toHaveCount(0);
 await expect(dialog.locator('[data-contract-readiness]')).toHaveCount(1);
 await expect(dialog.locator('[data-contract-readiness]')).not.toHaveAttribute('open','');
 await dialog.locator('[data-contract-readiness] summary').click();await expect(dialog.locator('.missing-terms')).toContainText('مبلغ توافقی');
 await dialog.locator('[data-action="review-contract-document"]').click();
 await expect(panel).toHaveAttribute('aria-labelledby','contract-tab-document');
 const paper=dialog.locator('#contractDocumentText');await expect(paper).toContainText('قرارداد');
 expect(await paper.textContent()).toBe(before.document||before.snapshot.document);
 const search=dialog.getByRole('searchbox',{name:'جست‌وجو در متن قرارداد'});
 await search.fill('قرارداد');await expect(paper.locator('mark').first()).toBeVisible();
 await search.press('Enter');await expect(paper.locator('mark.current-match')).toHaveCount(1);
 await search.press('Shift+Enter');await expect(paper.locator('mark.current-match')).toHaveCount(1);
 await search.fill('<script>');await expect(paper.locator('script')).toHaveCount(0);await expect(dialog.locator('[data-document-search-status]')).toHaveText('عبارت در متن پیدا نشد');
 await search.fill('');expect(await paper.textContent()).toBe(before.document||before.snapshot.document);
 await expect(dialog.locator('[data-document-next]')).toBeDisabled();
 const tabPosition=await tabs.boundingBox();await panel.evaluate(e=>e.scrollTop=e.scrollHeight);
 expect((await tabs.boundingBox()).y).toBe(tabPosition.y);await expect(tabs).toBeVisible();await expect(dialog.locator('[data-action="advance-dialog"]')).toBeVisible();
 await dialog.getByRole('tab',{name:'سند و الحاقیه‌ها',exact:true}).focus();await page.keyboard.press('ArrowLeft');await expect(dialog.getByRole('tab',{name:'تاریخچه',exact:true})).toHaveAttribute('aria-selected','true');
 await page.keyboard.press('Home');await expect(dialog.getByRole('tab',{name:'خلاصه و خدمات',exact:true})).toBeFocused();
 await page.keyboard.press('End');await expect(dialog.getByRole('tab',{name:'نسخه ثابت داده‌ها',exact:true})).toBeFocused();
 await dialog.getByRole('tab',{name:'سند و الحاقیه‌ها',exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect((await panel.boundingBox()).height).toBeGreaterThan(150);
 expect((await dialog.locator('.modal-footer').boundingBox()).y-(await paper.boundingBox()).y).toBeGreaterThan(100);
 await page.screenshot({path:testInfo.outputPath(`dossier-document-${width}.png`)});
 await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);
 expect(await(await request.get('/api/contracts/'+c.id,{headers})).json()).toEqual(before);expect(writes).toEqual([]);expect(errors).toEqual([]);
});
